/*
 * Prints the client schema that the Relay resolver docblocks in src/graph
 * declare, as one readable SDL file: docs/schema.graphql.
 *
 * That file is for reading only — relay-compiler never sees it. The
 * docblocks (`@relayType`, `@relayField`, `@live`, `@weak`) stay the single
 * source of truth; this script runs after every `bun run relay`, so the file
 * cannot drift.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

interface Field {
  name: string
  args: string
  type: string
  live: boolean
  description: string
}

interface TypeDef {
  name: string
  weak: boolean
  description: string
  fields: Field[]
}

const root = new URL('..', import.meta.url).pathname
const graphDir = join(root, 'src/graph')
const types = new Map<string, TypeDef>()
const typeOf = (name: string): TypeDef => {
  let def = types.get(name)
  if (!def) {
    def = { name, weak: false, description: '', fields: [] }
    types.set(name, def)
  }
  return def
}

for (const file of readdirSync(graphDir).filter((f) => f.endsWith('.ts')).sort()) {
  const source = readFileSync(join(graphDir, file), 'utf8')
  for (const [, body] of source.matchAll(/\/\*\*([\s\S]*?)\*\//g)) {
    const lines = (body ?? '')
      .split('\n')
      .map((line) => line.replace(/^\s*\*\s?/, '').trimEnd())
      .filter((line) => line.trim() !== '')
    const tags = lines.filter((line) => line.trim().startsWith('@'))
    const description = lines
      .filter((line) => !line.trim().startsWith('@'))
      .join(' ')
      .replace(/\s+/g, ' ')
      .trim()

    const typeTag = tags.find((t) => t.startsWith('@relayType'))
    if (typeTag) {
      const def = typeOf(typeTag.replace('@relayType', '').trim())
      def.weak = tags.some((t) => t.startsWith('@weak'))
      if (description) def.description = description
      continue
    }
    const fieldTag = tags.find((t) => t.startsWith('@relayField'))
    if (!fieldTag) continue
    const match = /@relayField\s+(\w+)\.(\w+)(\([^)]*\))?\s*:\s*(.+)$/.exec(fieldTag.trim())
    if (!match) throw new Error(`${file}: unreadable docblock "${fieldTag}"`)
    const [, typeName, name, args = '', type] = match
    typeOf(typeName!).fields.push({
      name: name!,
      args,
      type: type!.trim(),
      live: tags.some((t) => t.startsWith('@live')),
      description,
    })
  }
}

const block = (text: string, indent = '') => (text ? `${indent}"""\n${indent}${text}\n${indent}"""\n` : '')

const order = ['Query', ...[...types.keys()].filter((n) => n !== 'Query').sort()]
const out: string[] = [
  '# GENERATED by scripts/print-schema.ts — do not edit; `bun run relay` rewrites it.',
  '#',
  "# The client schema charaktail's Relay resolvers declare, for reading.",
  '# relay-compiler never reads this file: the @relayType / @relayField',
  '# docblocks in src/graph are the source of truth.',
  '#',
  '# @live  — a live resolver: re-read whenever the local state it watches changes.',
  '# @weak  — a weak type: a plain value with no identity of its own.',
  '# Types without @weak are model types with an id, resolved from that id.',
  '',
  'directive @live on FIELD_DEFINITION',
  'directive @weak on OBJECT',
  '',
]
for (const name of order) {
  const def = types.get(name)
  if (!def) continue
  out.push(block(def.description).trimEnd())
  out.push(`type ${name}${def.weak ? ' @weak' : ''} {`)
  if (!def.weak && name !== 'Query') out.push('  id: ID!')
  for (const field of def.fields) {
    if (field.description) out.push(block(field.description, '  ').trimEnd())
    out.push(`  ${field.name}${field.args}: ${field.type}${field.live ? ' @live' : ''}`)
  }
  out.push('}', '')
}
const text = out.filter((line, i, all) => !(line === '' && all[i - 1] === '')).join('\n')
writeFileSync(join(root, 'docs/schema.graphql'), text.replace(/^\n+/, ''))
console.log(`docs/schema.graphql — ${types.size} types, ${[...types.values()].reduce((n, t) => n + t.fields.length, 0)} fields`)
